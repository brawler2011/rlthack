import pytest

from app.ml.text import clean_for_embedding, lot_text


@pytest.mark.parametrize(
    ("raw", "clean"),
    [
        (
            "Поставка хозяйственных товаров (мешки), для нужд СПб ГБУЗ «Городская поликлиника "
            "№ 93» в 2024 году для субъектов малого предпринимательства",
            "хозяйственных товаров (мешки)",
        ),
        ("ПОСТАВКА НАБОРОВ РЕАГЕНТОВ ДЛЯ НУЖД СПБ ГБУЗ КВД №11 В 2024 ГОДУ.", "наборов реагентов"),
        (
            "Поставка продуктов питания для ГБДОУ детский сад № 70 Приморского района "
            "Санкт-Петербурга в июне 2024 года",
            "продуктов питания",
        ),
        (
            "Преподавательские услуги (п.33 ч.1 ст.93 Федерального закона №44-ФЗ)",
            "преподавательские услуги",
        ),
        ("Оказание услуг  по проведению дезинфекции помещений", "проведению дезинфекции помещений"),
        ("Картридж для офисной техники HP 2035", "картридж для офисной техники hp 2035"),
        ("Подготовка и поверка_Весы настольные_1 шт_", "подготовка и поверка весы настольные"),
        ("Поставка", "поставка"),  # nothing meaningful left: keep the plain text
        (None, ""),
    ],
)
def test_clean_for_embedding(raw, clean):
    assert clean_for_embedding(raw) == clean


def test_lot_text_dedupes_and_caps():
    names = ["Крупа манная", "крупа  манная", None, *[f"товар {i}" for i in range(20)]]
    text = lot_text("Поставка крупы для нужд ГБОУ школа № 5", names)

    parts = text.split("; ")
    assert parts[:2] == ["крупы", "крупа манная"]
    assert len(parts) == 11
