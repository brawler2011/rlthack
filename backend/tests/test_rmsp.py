from datetime import date

from app.etl.rmsp import parse_xml

XML = """<?xml version="1.0" encoding="windows-1251"?>
<Файл ИдФайл="x" ВерсФорм="4.06" ТипИнф="РЕЕСТРМСП" КолДок="3">
<Документ ИдДок="1" ДатаСост="10.09.2026" ДатаВклМСП="10.08.2016" ВидСубМСП="1" КатСубМСП="1"
  ССЧР="12">
  <ОргВклМСП НаимОрг="ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ «ВЕСЫ»" НаимОргСокр="ООО «ВЕСЫ»"
    ИННЮЛ="7802587594" ОГРН="1027801234567"/>
  <СведМН КодРегион="78"><Регион Тип="ГОРОД" Наим="САНКТ-ПЕТЕРБУРГ"/></СведМН>
  <СвОКВЭД>
    <СвОКВЭДОсн КодОКВЭД="28.29" НаимОКВЭД="Производство прочих машин" ВерсОКВЭД="2014"/>
    <СвОКВЭДДоп КодОКВЭД="46.69" НаимОКВЭД="Торговля оптовая" ВерсОКВЭД="2014"/>
  </СвОКВЭД>
  <СвПрод КодПрод="28.29.31" НаимПрод="Весы" ПрОтнПрод="0"/>
</Документ>
<Документ ИдДок="2" ДатаВклМСП="01.08.2020" ВидСубМСП="2" КатСубМСП="1">
  <ИПВклМСП ИННФЛ="500100732259" ОГРНИП="300000000000000">
    <ФИОИП Фамилия="ИВАНОВ" Имя="ИВАН" Отчество="ИВАНОВИЧ"/>
  </ИПВклМСП>
  <СведМН КодРегион="50"/>
  <СвОКВЭД><СвОКВЭДОсн КодОКВЭД="47.11" НаимОКВЭД="Торговля розничная" ВерсОКВЭД="2014"/></СвОКВЭД>
</Документ>
<Документ ИдДок="3" ДатаВклМСП="01.08.2020" ВидСубМСП="1" КатСубМСП="2">
  <ОргВклМСП НаимОрг="ООО «ДАЛЕКО»" ИННЮЛ="2500000001" ОГРН="1"/>
  <СведМН КодРегион="25"/>
</Документ>
</Файл>
"""


def test_parse_xml_filters_by_region_or_inn():
    raw = XML.encode("cp1251")
    companies = parse_xml(raw, regions={"78", "47"}, inns={"500100732259"})

    assert [c.inn for c in companies] == ["7802587594", "500100732259"]
    org, ip = companies
    assert org.name == "ООО «ВЕСЫ»" and not org.is_individual
    assert (org.region, org.category, org.headcount) == ("78", 1, 12)
    assert org.msp_since == date(2016, 8, 10)
    assert (org.okved_main, org.okved_extra, org.products) == ("28.29", ["46.69"], ["28.29.31"])
    assert ip.name == "ИП ИВАНОВ ИВАН ИВАНОВИЧ" and ip.is_individual
    assert ip.okved_main == "47.11" and ip.headcount is None
